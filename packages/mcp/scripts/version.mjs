// Writes src/version.ts from the CLI's package.json, so every part of ynm (telemetry's
// service.version, the MCP server's serverInfo.version, `ynm telemetry registry`, `--version`)
// reports one version: ynm's release, which is @ynm/cli's. It is compiled in, not read at
// runtime (a bundled binary has no package.json beside it). `pnpm gen:version` runs this.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
const { version } = JSON.parse(
  readFileSync(new URL("../../cli/package.json", import.meta.url), "utf8")
);
const file = new URL("../src/version.ts", import.meta.url);
const text = `// Generated by scripts/version.mjs from packages/cli/package.json at build time; do not edit.\nexport const RELEASE_VERSION = "${version}";\n`;
if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
