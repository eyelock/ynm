// Checks ynm's telemetry registry (telemetry/registry, Weaver's format) and generates the
// TypeScript constants from it. Weaver itself is not needed: this reads the same YAML.
//
//   node scripts/gen-telemetry.mjs           write packages/telemetry/src/registry.gen.ts
//   node scripts/gen-telemetry.mjs --check   exit 1 when that file is not current
//
// Checks: every own name is under `ynm.`; every `ref` names an attribute of ynm's or one in the
// pinned semantic-conventions release, which must be the installed one; every metric attribute
// has a declared cardinality, and their product fits the metric's declared limit.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse } from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const registryDir = join(root, "telemetry", "registry");
export const OUTPUT = join(root, "packages", "telemetry", "src", "registry.gen.ts");

/** The registry as data: the manifest and every group, in file order. */
export function loadRegistry() {
  const manifest = parse(readFileSync(join(registryDir, "registry_manifest.yaml"), "utf8"));
  const groups = [];
  for (const file of readdirSync(registryDir).sort()) {
    if (!file.endsWith(".yaml") || file === "registry_manifest.yaml") continue;
    groups.push(...(parse(readFileSync(join(registryDir, file), "utf8")).groups ?? []));
  }
  return { manifest, groups };
}

/** Attribute names of the installed semantic conventions, and its version. */
async function upstream() {
  const require = createRequire(join(root, "packages", "telemetry", "package.json"));
  const entry = require.resolve("@opentelemetry/semantic-conventions/incubating");
  let dir = dirname(entry);
  while (!readdirSync(dir).includes("package.json")) dir = dirname(dir);
  const { version } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const mod = await import(pathToFileURL(entry).href);
  const names = new Set(
    Object.entries(mod)
      .filter(([k, v]) => k.startsWith("ATTR_") && typeof v === "string")
      .map(([, v]) => v)
  );
  return { version, names };
}

const constName = (prefix, id) => `${prefix}_${id.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase()}`;

function check({ manifest, groups }, up) {
  const problems = [];
  if (`v${up.version}` !== manifest.semconv_version)
    problems.push(
      `the registry pins semantic conventions ${manifest.semconv_version}, but ${up.version} is installed`
    );
  const own = new Map();
  for (const g of groups)
    for (const a of g.type === "attribute_group" ? (g.attributes ?? []) : []) {
      if (!a.id?.startsWith("ynm.")) problems.push(`${g.id}: attribute ${a.id} is not under ynm.`);
      own.set(a.id, a);
    }
  const known = (id) => own.has(id) || up.names.has(id);
  for (const g of groups) {
    for (const a of g.attributes ?? [])
      if (a.ref && !known(a.ref)) problems.push(`${g.id}: ${a.ref} is not ynm's or in ${manifest.semconv_version}`);
    if (g.type === "event" && !g.name?.startsWith("ynm.")) problems.push(`${g.id}: event ${g.name} is not under ynm.`);
    if (g.type !== "metric") continue;
    if (!g.metric_name?.startsWith("ynm.")) problems.push(`${g.id}: metric ${g.metric_name} is not under ynm.`);
    const ann = g.annotations?.ynm ?? {};
    const declared = ann.attribute_cardinality ?? {};
    let product = 1;
    for (const a of g.attributes ?? []) {
      const n = declared[a.ref] ?? own.get(a.ref)?.annotations?.ynm?.cardinality;
      if (!n) problems.push(`${g.id}: ${a.ref} has no declared cardinality`);
      else product *= n;
    }
    if (!ann.cardinality_limit) problems.push(`${g.id}: no cardinality_limit`);
    else if (product > ann.cardinality_limit)
      problems.push(`${g.id}: attributes allow ${product} series, over the limit ${ann.cardinality_limit}`);
  }
  return problems;
}

/** The generated TypeScript for a registry. Deterministic: file order, no dates. */
export function render(registry) {
  const { manifest, groups } = registry;
  const lines = [
    "// Generated by scripts/gen-telemetry.mjs from telemetry/registry; do not edit. Run `make gen`.",
    "",
    `/** The semantic-conventions release the registry is pinned to. */`,
    `export const SEMCONV_VERSION = ${JSON.stringify(manifest.semconv_version)};`,
    "",
    "// ynm's attributes",
  ];
  const refs = new Set();
  for (const g of groups) {
    for (const a of g.attributes ?? []) if (a.ref && !a.ref.startsWith("ynm.")) refs.add(a.ref);
    if (g.type !== "attribute_group") continue;
    for (const a of g.attributes ?? []) {
      lines.push(`export const ${constName("ATTR", a.id)} = ${JSON.stringify(a.id)};`);
      for (const m of a.type?.members ?? [])
        lines.push(`export const ${constName("ATTR", `${a.id}_VALUE_${m.id}`)} = ${JSON.stringify(m.value)};`);
    }
  }
  lines.push("", `// Upstream attributes ynm uses (semantic conventions ${manifest.semconv_version})`);
  for (const id of [...refs].sort()) lines.push(`export const ${constName("ATTR", id)} = ${JSON.stringify(id)};`);
  lines.push("", "// Events");
  for (const g of groups.filter((x) => x.type === "event"))
    lines.push(`export const ${constName("EVENT", g.name)} = ${JSON.stringify(g.name)};`);
  lines.push("", "// Metrics");
  const limits = {};
  for (const g of groups.filter((x) => x.type === "metric")) {
    lines.push(`export const ${constName("METRIC", g.metric_name)} = ${JSON.stringify(g.metric_name)};`);
    limits[g.metric_name] = g.annotations.ynm.cardinality_limit;
  }
  lines.push(
    "",
    "/** Each metric's declared cardinality limit, which the SDK enforces. */",
    `export const METRIC_CARDINALITY_LIMITS: Readonly<Record<string, number>> = ${JSON.stringify(limits, null, 2)};`,
    "",
    "/** The whole registry, as `ynm telemetry registry --format json` prints it. */",
    `export const REGISTRY = ${JSON.stringify({ ...manifest, groups }, null, 2)} as const;`,
    ""
  );
  return lines.join("\n");
}

/** Checks the registry and returns the generated file's text; throws listing every problem. */
export async function generate() {
  const registry = loadRegistry();
  const problems = check(registry, await upstream());
  if (problems.length) throw new Error(`telemetry registry:\n  ${problems.join("\n  ")}`);
  return render(registry);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const text = await generate();
    if (process.argv.includes("--check")) {
      const current = readFileSync(OUTPUT, "utf8");
      if (current !== text) {
        console.error(`${OUTPUT} is not current; run \`make gen\``);
        process.exit(1);
      }
    } else {
      writeFileSync(OUTPUT, text);
      console.log(OUTPUT);
    }
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}
