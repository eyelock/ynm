// Regenerates the generated parts of the docs from the built packages, and checks links.
//
//   node scripts/gen-docs.mjs                 write into docs/
//   node scripts/gen-docs.mjs --out <dir>     write the same files under <dir> (drift test)
//   node scripts/gen-docs.mjs --check-links   report broken relative links and anchors; exit 1
//
// Fully generated: docs/reference/cli.md, docs/reference/mcp.md, docs/tutorial/manual-test-plan.md.
// Partly generated: the regions between `<!-- gen:NAME -->` and `<!-- /gen:NAME -->` in
// docs/reference/{configuration,record-format,memory-types}.md; the prose around them is edited
// by hand. Output is deterministic: no dates, sorted inputs. Needs `pnpm build` first.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docs = join(root, "docs");
const load = (rel) => import(pathToFileURL(join(root, rel)).href);
const requireFromService = createRequire(join(root, "packages", "service", "package.json"));
const { z } = await import(pathToFileURL(requireFromService.resolve("zod")).href);

const GENERATED_NOTE =
  "<!-- Generated by scripts/gen-docs.mjs from the built packages. Do not edit; run `make docs-gen`. -->";

