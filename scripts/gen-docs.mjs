// Link checker

function markdownFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...markdownFiles(p));
    else if (name.endsWith(".md")) out.push(p);
  }
  return out;
}

/** Relative links and anchors in docs/ must resolve. Root-absolute links resolve from docs/. */
function checkLinks() {
  const anchors = new Map();
  const anchorsOf = (file) => {
    if (!anchors.has(file)) {
      const slug = slugger();
      anchors.set(file, new Set(headingsOf(readFileSync(file, "utf8")).map((h) => slug(h.text))));
    }
    return anchors.get(file);
  };
  const broken = [];
  for (const file of markdownFiles(docs)) {
    const text = readFileSync(file, "utf8")
      .replace(/```[\s\S]*?```/g, "")
      .replace(/`[^`\n]*`/g, "");
    for (const m of text.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
      const target = m[1];
      if (/^[a-z]+:/i.test(target) || target.startsWith("//")) continue;
      const [path, anchor] = target.split("#");
      const dest = path
        ? path.startsWith("/")
          ? join(docs, path)
          : resolve(dirname(file), path)
        : file;
      const where = relative(root, file);
      let exists = false;
      try {
        exists = statSync(dest).isFile() || statSync(dest).isDirectory();
      } catch {}
      if (!exists) {
        broken.push(`${where}: ${target} (no such file)`);
        continue;
      }
      if (anchor && dest.endsWith(".md") && !anchorsOf(dest).has(anchor))
        broken.push(`${where}: ${target} (no such heading)`);
    }
  }
  return broken;
}

