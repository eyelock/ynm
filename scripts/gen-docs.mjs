async function mcpReference() {
  const { createYnmServer } = await load("packages/mcp/dist/server.js");
  const { TOOL_SPECS } = await load("packages/service/dist/tools.js");
  const server = createYnmServer({ cwd: root }, async () => {
    throw new Error("the docs generator never opens a store");
  });
  const tools = server._registeredTools;
  const resources = server._registeredResources;
  const templates = server._registeredResourceTemplates;
  const prompts = server._registeredPrompts;
  const instructions = server.server?._instructions;
  if (!tools || !resources || !templates || !prompts || !instructions)
    throw new Error("McpServer internals changed; update mcpReference in scripts/gen-docs.mjs");

  const out = [
    GENERATED_NOTE,
    "",
    "# MCP reference",
    "",
    "What `ynm serve` exposes to an MCP client: ten tools, four resources and three prompts,",
    "generated from the server definition. Every tool has a CLI command with the same input; see",
    "the [CLI reference](cli.md).",
    "",
    "## Server instructions",
    "",
    "Sent to the client in the `initialize` result:",
    "",
    ...instructions.split("\n").map((l) => `> ${l}`),
    "",
    "## Tools",
    "",
    table(
      ["Tool", "CLI command", "Read-only", "Destructive"],
      TOOL_SPECS.map((t) => {
        const a = tools[t.name]?.annotations ?? {};
        return [
          `[\`${t.name}\`](#${t.name})`,
          `[\`ynm ${t.command}\`](cli.md#ynm-${t.command})`,
          a.readOnlyHint ? "yes" : "no",
          a.destructiveHint ? "yes" : "no",
        ];
      })
    ),
    "",
    "A tool result carries the payload as JSON text and as `structuredContent: { data, guidance }`.",
    "When `guidance` is set it is also appended to the text after a blank line as",
    "`Guidance: ...`. A failed call returns `isError: true` with the message as text.",
    "",
  ];
  for (const t of TOOL_SPECS) {
    const rows = schemaRows(jsonSchema(t.input));
    out.push(`### ${t.name}`, "", t.description, "", `CLI: \`ynm ${t.command}\`.`, "");
    if (rows.length)
      out.push(
        table(
          ["Field", "Type", "Required", "Default", "Description"],
          rows.map((r) => [
            code(r.name),
            r.type,
            r.required ? "yes" : "",
            defaultText(r.default),
            r.description,
          ])
        ),
        ""
      );
    else out.push("No input fields.", "");
  }
  out.push(
    "## Resources",
    "",
    table(
      ["URI", "MIME type", "Description"],
      [
        ...Object.entries(resources).map(([uri, r]) => [
          code(uri),
          code(r.metadata?.mimeType ?? ""),
          r.metadata?.description ?? "",
        ]),
        ...Object.values(templates).map((r) => [
          code(r.resourceTemplate.uriTemplate?.toString?.() ?? r.resourceTemplate._uriTemplate.template),
          code(r.metadata?.mimeType ?? ""),
          `${r.metadata?.description ?? ""} (template)`,
        ]),
      ]
    ),
    "",
    "## Prompts",
    "",
    "Each prompt takes no arguments and returns one user message holding a guidance document. The",
    "same documents are written into client instructions by `ynm client install`.",
    "",
    table(
      ["Prompt", "Description"],
      Object.entries(prompts).map(([name, p]) => [code(name), p.description ?? ""])
    ),
    ""
  );
  return `${out.join("\n").replace(/\n+$/, "")}\n`;
}

