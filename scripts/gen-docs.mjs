// Shared rendering helpers

const code = (s) => `\`${String(s).replace(/`/g, "'")}\``;
const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
const table = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `|${head.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
  ].join("\n");
const toKebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const jsonSchema = (schema) => z.toJSONSchema(schema, { io: "input", unrepresentable: "any" });

/** Drops `null` from `anyOf` (nullable fields) and reports it. */
function unwrap(s) {
  if (s?.anyOf) {
    const rest = s.anyOf.filter((x) => x.type !== "null");
    if (rest.length === 1)
      return {
        ...rest[0],
        description: s.description ?? rest[0].description,
        default: s.default ?? rest[0].default,
        nullable: rest.length < s.anyOf.length,
      };
  }
  return s ?? {};
}

function range(s) {
  const big = (n) => n === undefined || Math.abs(n) >= Number.MAX_SAFE_INTEGER;
  let lo = s.minimum ?? (s.exclusiveMinimum === 0 && s.type === "integer" ? 1 : undefined);
  const hi = big(s.maximum) ? undefined : s.maximum;
  if (big(lo)) lo = undefined;
  if (s.exclusiveMinimum !== undefined && lo === undefined) return ` > ${s.exclusiveMinimum}`;
  if (lo !== undefined && hi !== undefined) return ` ${lo}..${hi}`;
  if (lo !== undefined) return ` >= ${lo}`;
  if (hi !== undefined) return ` <= ${hi}`;
  return "";
}

/** A short, readable type for a JSON Schema node. */
function typeText(raw) {
  const s = unwrap(raw);
  let t;
  if (s.enum) t = s.enum.map((v) => code(v)).join(" | ");
  else if (s.const !== undefined) t = code(JSON.stringify(s.const));
  else if (s.type === "array") {
    const item = unwrap(s.items);
    t = `array of ${item.type === "object" ? "object" : typeText(item)}`;
  } else if (s.type === "object") t = "object";
  else if (s.type === "string") {
    t = s.format === "date-time" ? "date-time" : "string";
    if (s.maxLength !== undefined) t += ` (max ${s.maxLength})`;
  } else if (s.type === "integer" || s.type === "number") t = `${s.type}${range(s)}`;
  else if (s.type === "boolean") t = "boolean";
  else t = "any";
  return s.nullable ? `${t} or null` : t;
}

function defaultText(v) {
  if (v === undefined) return "";
  if (typeof v === "string") return code(v);
  return code(JSON.stringify(v));
}

/**
 * Flattens an object schema into rows. Arrays of objects and nested objects expand into
 * `parent[].child` and `parent.child` rows. `defaults` is the parsed empty value, used where a
 * default sits on a parent object rather than on the leaf.
 */
function schemaRows(json, { prefix = "", defaults, expand = true } = {}) {
  const rows = [];
  const required = new Set(json.required ?? []);
  for (const [name, raw] of Object.entries(json.properties ?? {})) {
    const s = unwrap(raw);
    const path = `${prefix}${name}`;
    const dflt = s.default !== undefined ? s.default : defaults?.[name];
    const isObject = s.type === "object" && s.properties;
    const isObjArray = s.type === "array" && unwrap(s.items).type === "object";
    const description = s.description ?? "";
    rows.push({
      name: path,
      type: typeText(s),
      required: required.has(name) && s.default === undefined,
      default: isObject ? undefined : dflt,
      description,
      documented: s.description !== undefined,
    });
    if (expand && isObject)
      rows.push(
        ...schemaRows(s, {
          prefix: `${path}.`,
          defaults: dflt && typeof dflt === "object" ? dflt : undefined,
        })
      );
    if (expand && isObjArray)
      rows.push(...schemaRows(unwrap(s.items), { prefix: `${path}[].` }));
  }
  return rows;
}

