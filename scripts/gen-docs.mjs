function fillBlocks(markdown, blocks, file) {
  let text = markdown;
  for (const [name, body] of Object.entries(blocks)) {
    const re = new RegExp(`(<!-- gen:${name} -->)[\\s\\S]*?(<!-- /gen:${name} -->)`);
    if (!re.test(text)) throw new Error(`${file}: missing <!-- gen:${name} --> block`);
    text = text.replace(re, (_, a, b) => `${a}\n${body}\n${b}`);
  }
  return text;
}

