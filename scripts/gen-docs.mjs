/**
 * Strips the type suffixes flagsFromSchema appends, and drops a description that is only the
 * field name (flagsFromSchema's fallback when the schema has none).
 */
function flagDescription(flag, description = "") {
  const d = description.replace(/( \((JSON array|JSON object|number|default: [^)]*)\))+$/, "");
  const bare = d.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
  return bare === flag ? "" : d;
}

async function cliReference() {
  const dir = join(root, "packages", "cli", "dist", "commands");
  const { YnmCommand } = await load("packages/cli/dist/lib/base.js");
  const { TOOL_SPECS } = await load("packages/service/dist/tools.js");
  const { RecordFilterSchema } = await load("packages/model/dist/index.js");
  const base = YnmCommand.baseFlags;
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".js"))
    .sort();
  const out = [
    GENERATED_NOTE,
    "",
    "# CLI reference",
    "",
    "Every `ynm` command, generated from the command definitions. `ynm <command> --help` prints the",
    "same flags. Flags generated from a tool's input schema show that schema's default; the MCP tool",
    "with the same input is listed in the [MCP reference](mcp.md).",
    "",
    "## Common flags",
    "",
    table(
      ["Flag", "Type", "Default", "Description"],
      [
        ["`--json`", "boolean", code("false"), base.json.description],
        ["`--cwd <value>`", "string", "", base.cwd.description],
      ]
    ),
    "",
    "Every command except `serve` takes both; `serve` takes `--cwd` only. Exit codes and the JSON",
    "shapes are in [Exit codes and JSON output](exit-codes-and-json.md).",
    "",
    "## Commands",
    "",
    "__INDEX__",
    "",
  ];
  const indexRows = [];
  for (const f of files) {
    const id = f.replace(/\.js$/, "");
    const C = (await load(`packages/cli/dist/commands/${f}`)).default;
    const tool = TOOL_SPECS.find((t) => t.command === id);
    const schema = tool?.input ?? (id === "list" || id === "export" ? RecordFilterSchema : null);
    const props = schema ? (jsonSchema(schema).properties ?? {}) : {};
    const propByFlag = new Map(Object.entries(props).map(([k, v]) => [toKebab(k), unwrap(v)]));
    indexRows.push([`[\`${id}\`](#ynm-${id})`, C.description ?? ""]);

    const args = Object.entries(C.args ?? {});
    const flags = Object.entries(C.flags ?? {});
    const common = flags.filter(([, fl]) => fl === base.json || fl === base.cwd);
    const own = flags.filter(([, fl]) => fl !== base.json && fl !== base.cwd);
    const usage = [
      "ynm",
      id,
      ...args.map(([n, a]) => (a.required ? `<${n}>` : `[${n}]`)),
      ...(own.length || common.length ? ["[flags]"] : []),
    ].join(" ");

    out.push(`## ynm ${id}`, "", C.description ?? "", "", "```text", usage, "```", "");
    if (args.length) {
      out.push(
        table(
          ["Argument", "Required", "Values", "Description"],
          args.map(([n, a]) => [
            code(n),
            a.required ? "yes" : "no",
            (a.options ?? []).map(code).join(", "),
            a.description ?? "",
          ])
        ),
        ""
      );
    }
    if (own.length) {
      const rows = own.map(([n, fl]) => {
        const prop = propByFlag.get(n);
        let type;
        if (fl.type === "boolean") type = "boolean";
        else if (fl.options) type = fl.options.map(code).join(" | ");
        else if (prop?.type === "array" && fl.multiple) type = typeText(prop.items);
        else if (prop?.type === "array") type = "JSON array";
        else if (prop?.type === "object") type = "JSON object";
        else if (prop) type = typeText(prop);
        else if (String(fl.parse).includes("Expected an integer")) type = "integer";
        else type = "string";
        if (fl.multiple) type += ", repeatable";
        const name =
          fl.type === "boolean"
            ? fl.allowNo
              ? `\`--[no-]${n}\``
              : `\`--${n}\``
            : `\`--${n} <value>\``;
        const dflt = fl.default !== undefined ? fl.default : prop?.default;
        return [
          name,
          type,
          fl.required ? "yes" : "",
          defaultText(dflt),
          flagDescription(n, fl.description),
        ];
      });
      out.push(table(["Flag", "Type", "Required", "Default", "Description"], rows), "");
    }
    if (common.length) out.push(`Common flags: ${common.map(([n]) => `\`--${n}\``).join(", ")}.`, "");
    if (tool) out.push(`MCP tool: [\`${tool.name}\`](mcp.md#${tool.name}).`, "");
    const examples = (C.examples ?? []).map((e) =>
      String(typeof e === "string" ? e : e.command)
        .replace(/<%= config\.bin %>/g, "ynm")
        .replace(/<%= command\.id %>/g, id)
    );
    if (examples.length) out.push("Examples:", "", "```bash", ...examples, "```", "");
  }
  out[out.indexOf("__INDEX__")] = table(["Command", "Description"], indexRows);
  return `${out.join("\n").replace(/\n+$/, "")}\n`;
}

