/** docsify's heading slug: lowercased, punctuation dropped, spaces to dashes, per-page counter. */
function slugger() {
  const seen = new Map();
  return (heading) => {
    let slug = heading
      .trim()
      .replace(/`/g, "")
      .toLowerCase()
      .replace(/<[^>]+>/g, "")
      .replace(/[ -⁯⸀-⹿\\'!"#$%&()*+,./:;<=>?@[\]^`{|}~]/g, "")
      .replace(/\s/g, "-")
      .replace(/-+/g, "-")
      .replace(/^(\d)/, "_$1");
    const n = seen.has(slug) ? seen.get(slug) + 1 : 0;
    seen.set(slug, n);
    if (n) slug = `${slug}-${n}`;
    return slug;
  };
}

function headingsOf(markdown) {
  const out = [];
  let fence = false;
  for (const line of markdown.split("\n")) {
    if (/^\s*```/.test(line)) fence = !fence;
    if (fence) continue;
    const h = /^(#{1,6})\s+(.*?)\s*#*\s*$/.exec(line);
    if (h) out.push({ level: h[1].length, text: h[2] });
  }
  return out;
}

function manualTestPlan() {
  const dir = join(docs, "tutorial");
  const files = readdirSync(dir)
    .filter((f) => /^\d{2}-.*\.md$/.test(f))
    .sort();
  const out = [
    GENERATED_NOTE,
    "",
    "# Manual test plan",
    "",
    "Every step of every tutorial, in order, with a link to it. Run the tutorials top to bottom to",
    "cover the happy path; tick steps off here when testing by hand. A model can run the same steps",
    "for you; see [Running tutorials as evals](RUNNING.md).",
    "",
    "Steps marked with a condition need a key or an optional tool and may be skipped.",
    "",
  ];
  for (const f of files) {
    const n = Number(f.slice(0, 2));
    const lines = readFileSync(join(dir, f), "utf8").split("\n");
    const slug = slugger();
    let title = f;
    let heading = null;
    let pendingSkip;
    const rows = [];
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const h = /^(#{1,6})\s+(.*?)\s*$/.exec(line);
      if (h) {
        const anchor = slug(h[2]);
        if (h[1].length === 1) title = h[2];
        else heading = { text: h[2], anchor, blocks: 0 };
        continue;
      }
      const skip = /^<!--\s*tutorial:\s*skip unless\s+([A-Z0-9_]+)\s*-->$/.exec(line.trim());
      if (skip) {
        pendingSkip = skip[1];
        continue;
      }
      if (/^\s*```/.test(line)) {
        const body = [];
        for (i += 1; i < lines.length && lines[i].trim() !== "```"; i++) body.push(lines[i]);
        if (line.trim() === "```bash" && heading) {
          heading.blocks += 1;
          const first = body.map((l) => l.trim()).find((l) => l && !l.startsWith("#")) ?? "";
          rows.push([
            `${n}.${rows.length + 1}`,
            `[${heading.text}${heading.blocks > 1 ? ` (${heading.blocks})` : ""}](${f}#${heading.anchor})`,
            first ? code(first.length > 72 ? `${first.slice(0, 69)}...` : first) : "",
            pendingSkip ? `needs ${code(pendingSkip)}` : "",
          ]);
        }
        pendingSkip = undefined;
        continue;
      }
      if (line.trim() !== "") pendingSkip = undefined;
    }
    out.push(
      `## [${title}](${f})`,
      "",
      table(["#", "Step", "First command", "Condition"], rows),
      ""
    );
  }
  return `${out.join("\n").replace(/\n+$/, "")}\n`;
}

